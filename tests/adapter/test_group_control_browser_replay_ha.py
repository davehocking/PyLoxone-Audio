"""Actual compiled browser service requests replayed through owning HA/native I/O.

The JSON is generated by tests/frontend/browser.mjs using invented HA exports.
The real UI browser uses a sink; this separate replay proves those exact service
payloads/targets reach the real owner, authenticated native peer and feedback.
This is not a claim of a live browser-to-household connection.
"""
from pathlib import Path
import hashlib
import json
import pytest
from homeassistant.exceptions import HomeAssistantError
from custom_components.loxone.pyloxone_api import audioserver as wire
from test_audio_grouping_ha import STATE, action, row, payload
from test_audio_grouping_ha import grouped_setup as grouped_setup
from test_audio_grouping_ha import audio_setup as audio_setup
from test_audioserver_playback import SyntheticAudioSocket
from test_audioserver_playback import rsa_key as rsa_key
from gm03_trace_support import VolumeFeedback


async def test_exact_rendered_browser_service_calls_reach_owning_native_targets(hass, grouped_setup, monkeypatch, rsa_key):
    root = Path(__file__).resolve().parents[2]
    trace = json.loads((root/'tests/frontend/browser-service-calls.json').read_text())
    asset = root/'adapters/pyloxone/frontend/dist/group-control-card-0.1.3.dev3.js'
    assert hashlib.sha256(asset.read_bytes()).hexdigest() == trace['asset_sha256']
    g = grouped_setup
    entry, co, ids = await g.setup()
    numbers = {entity_id:player for player,entity_id in ids.items()}
    co.audio_commands._credentials = lambda: ('synthetic-user','synthetic-active-token')
    sockets = []
    rows = []
    reject = False
    class Socket(SyntheticAudioSocket):
        async def send(self, message):
            nonlocal rows
            if message.startswith('audio/grouped/'):
                self.sent.append(message)
                _, _, mode, participants = message.split('/')
                self.queue.put_nowait(json.dumps({f'grouped_{mode}_result':{'players':[{'playerid':int(p),'mode':mode} for p in participants.split(',')]}}))
                return
            if message.startswith('audio/cfg/dgroup/update/'):
                self.sent.append(message)
                parts = message.split('/')
                name = parts[4]
                if reject:
                    self.queue.put_nowait(json.dumps({'dgroup_update_result':False}))
                    return
                members = tuple(int(p) for p in parts[5].split(',')) if len(parts)>5 else ()
                rows = [r for r in rows if r['group'] != name]
                if members: rows.append(row(name,members))
                await g.callbacks[entry.entry_id]['callback']({STATE:payload(*rows)})
                self.queue.put_nowait(json.dumps({'dgroup_update_result':{'id':name}}))
                return
            await super().send(message)
    def connect(*a, **k):
        s = Socket(rsa_key); sockets.append(s); return s
    monkeypatch.setattr(wire,'connect',connect)
    feedback=VolumeFeedback(hass,g,entry,ids)
    for request in trace['calls']:
        assert request['domain'] == 'media_player'
        target = request['target']['entity_id']
        assert target in numbers
        rows = [row(group['id'],tuple(numbers[i] for i in group['members'])) for group in request['groups']]
        rows.append(row('fixed',(5,6),'static'))
        await g.feed(entry,*rows)
        await g.callbacks[entry.entry_id]['callback']({f'volume-{p}':p*10 for p in ids})
        await hass.async_block_till_done()
        before = co.audio_grouping.native.snapshot.groups
        expected_volume=feedback.expected(g,co,target,request['data']['volume_level']) if request['service']=='volume_set' else None
        co.api.send_websocket_command.reset_mock()
        count = len(sockets)
        reject = request['mode'] == 'reject'
        call = hass.services.async_call(request['domain'],request['service'],request['data'],target=request['target'],blocking=True)
        if reject:
            with pytest.raises(HomeAssistantError): await call
        else:
            await call
        await hass.async_block_till_done()
        messages = [m for s in sockets[count:] for m in s.sent if m.startswith('audio/') and m != 'audio/cfg/getkey/full']
        service = request['service']
        if service == 'volume_set':
            assert messages == []
            # Literal historical public request has owner-corrected room scope.
            assert [tuple(c.args) for c in co.api.send_websocket_command.await_args_list]==expected_volume
            assert co.audio_grouping.native.snapshot.groups == before
        else:
            assert len(messages) == 1
            co.api.send_websocket_command.assert_not_awaited()
            if service in ('media_play','media_pause'):
                group = next(g for g in before if numbers[target] in g.players)
                assert messages == ['audio/grouped/'+('play' if service == 'media_play' else 'pause')+'/'+','.join(map(str,group.players))]
                assert co.audio_grouping.native.snapshot.groups == before
            elif reject:
                assert co.audio_grouping.native.snapshot.groups == before
                assert co.audio_grouping.native.uncertain
            else:
                expected = tuple(numbers[i] for i in request['groups'][0]['members'])
                expected = expected+tuple(numbers[i] for i in request['data']['group_members']) if service == 'join' else tuple(p for p in expected if p != numbers[target])
                assert next(g for g in co.audio_grouping.native.snapshot.groups if g.group_id == request['groups'][0]['id']).players == expected
        assert any(g.group_id == 'fixed' and g.players == (5,6) for g in co.audio_grouping.native.snapshot.groups)
        assert all(s.closed for s in sockets)
        assert not co.audio_grouping.native._scope
    assert len(trace['calls']) == 7
    feedback.remove()
